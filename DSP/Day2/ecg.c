bool dft_real_one_sided_f32(
    const float32_t *pSrc,
    uint32_t src_len,
    float32_t *pReal,
    float32_t *pImag,
    float32_t *pMagnitude,
    uint32_t output_capacity
)
{
    if ((pSrc == NULL) ||
        (pReal == NULL) ||
        (pImag == NULL) ||
        (pMagnitude == NULL) ||
        (src_len < 2U))
    {
        return false;
    }

    const uint32_t number_of_bins = (src_len / 2U) + 1U;

    /* Ngăn ghi vượt kích thước output. */
    if (output_capacity < number_of_bins)
    {
        return false;
    }

    const float32_t inverse_length = 1.0f / (float32_t)src_len;

    /* k là chỉ số bin tần số. */
    for (uint32_t k = 0U; k < number_of_bins; k++)
    {
        float32_t real_sum = 0.0f;
        float32_t imag_sum = 0.0f;

        /* n là chỉ số mẫu trong miền thời gian. */
        for (uint32_t n = 0U; n < src_len; n++)
        {
            float32_t angle =
                TWO_PI_F *
                (float32_t)k *
                (float32_t)n /
                (float32_t)src_len;

            float32_t cosine = arm_cos_f32(angle);
            float32_t sine   = arm_sin_f32(angle);

            real_sum += pSrc[n] * cosine;
            imag_sum -= pSrc[n] * sine;
        }

        pReal[k] = real_sum;
        pImag[k] = imag_sum;

        float32_t magnitude = 0.0f;

        arm_sqrt_f32(
            real_sum * real_sum +
            imag_sum * imag_sum,
            &magnitude
        );

        /*
         * Chuẩn hóa phổ theo N.
         * Đây là biên độ của phổ hai phía trước khi nhân đôi.
         */
        magnitude *= inverse_length;

        /*
         * Khi chuyển sang phổ một phía:
         * - DC tại k = 0 không nhân 2.
         * - Nyquist tại k = N/2 không nhân 2.
         * - Các bin nằm giữa nhân 2.
         */
        bool is_dc = (k == 0U);

        bool is_nyquist =
            ((src_len % 2U) == 0U) &&
            (k == (src_len / 2U));

        if ((!is_dc) && (!is_nyquist))
        {
            magnitude *= 2.0f;
        }

        pMagnitude[k] = magnitude;
    }

    return true;
}


